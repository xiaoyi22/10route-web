async function checkThroughput(stats) {
  assert(Array.isArray(stats.last10Minutes) && stats.last10Minutes.length >= 6, '真实接口必须提供完整分钟窗口');
  const complete = stats.last10Minutes.slice(-6, -1);
  const rpm = complete.reduce((total, bucket) => total + bucket.requests, 0) / 5;
  const input = complete.reduce((total, bucket) => total + bucket.promptTokens, 0) / 5;
  const output = complete.reduce((total, bucket) => total + bucket.completionTokens, 0) / 5;
  const tpm = complete.reduce((total, bucket) => total + bucket.promptTokens + bucket.completionTokens, 0) / 5;
  await page.waitForFunction(expected => Object.entries(expected).every(([name, value]) => Number(document.querySelector('[data-testid="' + name + '"]')?.textContent.replaceAll(',', '')) === value), { 'throughput-rpm': rpm, 'throughput-tpm': tpm, 'throughput-input-tpm': input, 'throughput-output-tpm': output });
}
