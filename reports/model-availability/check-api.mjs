import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { parseEnv } from 'node:util';
const base = 'http://192.168.11.150:20128';
const path = '/api/model-availability';
const anonymous = await fetch(base + path);
assert.equal(anonymous.status, 401);
const env = parseEnv(await readFile('C:/Users/Administrator/.codex/credentials/10router-web.env', 'utf8'));
const login = await fetch(base + '/api/auth/login', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ password: env.TENROUTER_TEST_PASSWORD.trim() }) });
assert.equal(login.status, 200);
const cookie = login.headers.getSetCookie().map(item => item.split(';')[0]).join('; ');
const headers = { cookie, 'content-type': 'application/json' };
const response = await fetch(base + path, { headers });
assert.equal(response.status, 200);
const data = await response.json();
assert.equal(data.config.mode, 'observe');
assert.deepEqual(data.config.providers, []);
const conflict = await fetch(base + path, { method: 'PUT', headers, body: JSON.stringify({ revision: -1, config: data.config }) });
assert.equal(conflict.status, 409);
const invalid = await fetch(base + path, { method: 'POST', headers, body: JSON.stringify({ provider: data.rows[0].provider, connectionId: data.rows[0].connectionId, model: data.rows[0].model, action: 'invalid' }) });
assert.equal(invalid.status, 400);
const final = await (await fetch(base + path, { headers })).json();
assert.deepEqual(final.config, data.config);
const health = await fetch(base + '/api/health');
assert.equal(health.status, 200);
const report = { anonymousHttp: anonymous.status, loginHttp: login.status, readHttp: response.status, staleRuleHttp: conflict.status, invalidControlHttp: invalid.status, healthHttp: health.status, mode: data.config.mode, automaticProviders: data.config.providers, channels: data.rows.length, observedRequests: final.observedRequests, probeRequests: 0, passed: true };
await writeFile('reports/model-availability/api-acceptance.json', JSON.stringify(report, null, 2));
console.log(JSON.stringify(report));
